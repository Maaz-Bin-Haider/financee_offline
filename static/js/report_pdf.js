/* ============================================================
   report_pdf.js — the shared report PDF theme (FinanceePdf)

   Ported unchanged from the sibling Accounting-Plus-Inventory-
   System (feature commit 80e8f8a), where every report PDF is
   built through it. In this project it currently serves the
   Draft Invoices feature only: the Proforma Invoice, the
   Pending Drafts report and the two draft history exports
   (module "draft", slate accent). The older report screens keep
   their own generators. MODULE_ACCENT is kept whole so a screen
   moved onto the theme later keeps its colour.

   Load order: jsPDF, then jspdf-autotable (both in the page
   body, after jsPDF exists), then this file. The autotable copy
   in base.html's <head> runs before jsPDF exists and never
   attaches, so doc.autoTable would be undefined without the
   page's own copy.

   ── The shape, and why ──────────────────────────────────────
   The structure follows the GST report: a plain title block
   rather than a heavy colour band. A band spends the top 6% of
   every page on decoration; a title and a rule say the same
   thing and leave the space to the data.

   Colour is deliberately light. Each module keeps its own
   accent — Stock reads green, Profit amber — because those
   already carry meaning on screen, but the accent appears in
   only four places: the wordmark, the rule under the title, the
   summary chips and the table header. Header fills sit around
   92% lightness with same-hue dark text, so they read as tinted
   paper rather than blocks of colour.

   ── What every report carries ───────────────────────────────
   * its own name, top-left and again bottom-right, so a page
     separated from its report still says what it is;
   * an exact timestamp to the second;
   * "Generated by Financee ERP · Developed by Maaz Rehan",
     bottom-left on every page.

   The attribution is a footer rather than a watermark on
   purpose: a diagonal watermark sits over the figures, and a
   report whose numbers are harder to read is a worse report.

   ── Node and the browser ────────────────────────────────────
   Dual-mode: pure module first, browser global last, so a Node
   harness can require this file and render the real thing
   rather than a copy of it.
   ============================================================ */

(function (root, factory) {
  var api = factory();
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root) root.FinanceePdf = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function () {
  "use strict";

  /* ── Palette ──────────────────────────────────────────────
     tint  backs the table header and the summary chips
     ink   the same hue, dark enough to read as text on tint
     rule  the hairline between them, and the rule under the title

     Kept as RGB triples because that is what jsPDF takes; the
     hex equivalents are in the comments so they can be checked
     against the on-screen tokens. */
  var ACCENT = {
    blue:   { tint: [231, 238, 248], ink: [30, 58, 95],   rule: [199, 214, 234] }, /* #E7EEF8 #1E3A5F */
    green:  { tint: [230, 242, 236], ink: [31, 77, 58],   rule: [197, 222, 210] }, /* #E6F2EC #1F4D3A */
    amber:  { tint: [246, 238, 225], ink: [107, 68, 21],  rule: [227, 210, 184] }, /* #F6EEE1 #6B4415 */
    violet: { tint: [237, 234, 246], ink: [63, 49, 104],  rule: [214, 207, 234] }, /* #EDEAF6 #3F3168 */
    teal:   { tint: [228, 240, 241], ink: [31, 74, 80],   rule: [195, 221, 224] }, /* #E4F0F1 #1F4A50 */
    slate:  { tint: [234, 237, 242], ink: [43, 58, 79],   rule: [207, 215, 226] }, /* #EAEDF2 #2B3A4F */
  };

  /* Which module owns which accent. One place, so a report
     cannot quietly pick a colour nothing else uses. */
  var MODULE_ACCENT = {
    accounts: "blue",
    ledger: "slate",
    stock: "green",
    profit: "amber",
    monthly: "green",
    gst: "violet",
    dashboard: "teal",

    /* The four transaction documents. These are not reports — they go to a
       customer or a supplier rather than staying inside the business — but
       they share the theme so a company that sends an invoice and a
       statement in the same envelope sends one thing, not two.

       Sale and purchase take the direction's own colour; the two returns
       take amber and slate, because a return needs to be distinguishable
       from the document it reverses at a glance across a desk. */
    sale: "blue",
    purchase: "green",
    "sale-return": "amber",
    "purchase-return": "slate",

    /* The draft documents: the Pending Drafts report and the Proforma
       Invoice. Slate rather than sale's blue, deliberately -- a proforma
       that looks like the sale invoice invites being paid against, and the
       whole point of the document is that no payment is due on it. */
    draft: "slate",
  };

  var INK      = [30, 41, 59];
  var MUTED    = [100, 116, 139];
  var FAINT    = [148, 163, 184];
  var HAIRLINE = [226, 232, 240];
  var ZEBRA    = [248, 250, 252];

  /* Faint row tints for meaning the report already carries on
     screen. Deliberately weaker than the on-screen versions:
     print has no hover and no legend beside it. */
  var ROW = {
    loss:         [253, 240, 240],
    unclassified: [250, 243, 232],
    subtle:       [248, 250, 252],
  };

  /* Millimetres are the house unit. One report — the Detailed Ledger in
     its per-row card mode — draws 167 lines of hand-placed geometry in
     points, and rescaling 142 coordinates by hand to gain nothing visible
     would be a poor trade. So the theme is defined in mm and converted
     when a caller asks for points: identical output, either way.

     Font sizes are deliberately not scaled — jsPDF measures type in
     points whatever the document unit is. */
  var MM_TO_PT = 2.834645669;
  var MARGIN_MM = 14;

  /* Three-letter months, pinned. Left to toLocaleDateString,
     en-GB renders September as "Sept" while every other month
     is three letters, so a report's period line and its
     timestamp disagree about how long a month name is. */
  var MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

  function pad(n) { return n < 10 ? "0" + n : String(n); }

  /** A date as "03 Aug 2026". */
  function formatDate(d) {
    var x = (d instanceof Date) ? d : new Date(d);
    if (isNaN(x.getTime())) return String(d);
    return pad(x.getDate()) + " " + MONTHS[x.getMonth()] + " " + x.getFullYear();
  }

  /** Exact date and time, to the second: "03 Aug 2026 at 13:41:22". */
  function formatStamp(d) {
    var x = (d instanceof Date) ? d : (d ? new Date(d) : new Date());
    return formatDate(x) + " at " +
      pad(x.getHours()) + ":" + pad(x.getMinutes()) + ":" + pad(x.getSeconds());
  }

  /** A filename that sorts by date and carries the report name. */
  function filename(title, d) {
    var x = (d instanceof Date) ? d : new Date();
    return String(title).replace(/[^\w]+/g, "_").replace(/^_|_$/g, "") + "_" +
      x.getFullYear() + pad(x.getMonth() + 1) + pad(x.getDate()) + ".pdf";
  }

  function accentFor(opts) {
    if (opts.accent && ACCENT[opts.accent]) return ACCENT[opts.accent];
    var byModule = MODULE_ACCENT[opts.module];
    return ACCENT[byModule] || ACCENT.blue;
  }

  /**
   * Build a themed report document.
   *
   * @param {object} o
   *   jsPDF     the jsPDF constructor (browser: window.jspdf.jsPDF)
   *   title     the report name. Required — it is the one thing
   *             every page must state.
   *   module    'accounts'|'ledger'|'stock'|'profit'|'monthly'|
   *             'gst'|'dashboard'  — chooses the accent
   *   accent    overrides module, for a one-off
   *   context   what narrows the report: period, party, as-of
   *   summary   [[label, value], ...] rendered as soft chips
   *   head      array of column headings
   *   body      array of row arrays
   *   html      a selector for a table already in the DOM, instead
   *             of head/body — used by the dashboard modal exports
   *   orient    'p' | 'l'   (default portrait)
   *   columnStyles / didParseCell  passed through to autoTable
   *   draw(doc, ctx)        replaces the table entirely, for a
   *                         report whose body is not tabular
   *   afterTable(doc, y)    extra content below the table
   *   generatedAt           a Date, for a deterministic stamp
   *
   * @returns {object} the jsPDF document, footers already stamped
   */
  function build(o) {
    if (!o || !o.title) throw new Error("report_pdf: a report must state its title");
    var JsPDF = o.jsPDF;
    if (!JsPDF) throw new Error("report_pdf: pass the jsPDF constructor as opts.jsPDF");

    var A = accentFor(o);
    var stamp = formatStamp(o.generatedAt);
    var unit = o.unit === "pt" ? "pt" : "mm";
    var u = function (mm) { return unit === "pt" ? mm * MM_TO_PT : mm; };
    var MARGIN = u(MARGIN_MM);
    var doc = new JsPDF({
      orientation: o.orient === "l" ? "landscape" : "portrait",
      unit: unit,
      format: "a4",
    });
    var pW = doc.internal.pageSize.width;
    var pH = doc.internal.pageSize.height;

    /* ── Title block, redrawn on every page ── */
    function header() {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(15);
      doc.setTextColor(INK[0], INK[1], INK[2]);
      doc.text(String(o.title), MARGIN, u(16));

      doc.setFont("helvetica", "bold");
      doc.setFontSize(8.5);
      doc.setTextColor(A.ink[0], A.ink[1], A.ink[2]);
      doc.text("Financee ERP", pW - MARGIN, u(16), { align: "right" });

      doc.setFont("helvetica", "normal");
      doc.setFontSize(8.5);
      doc.setTextColor(MUTED[0], MUTED[1], MUTED[2]);
      if (o.context) doc.text(String(o.context), MARGIN, u(22));
      doc.text("Generated " + stamp, pW - MARGIN, u(22), { align: "right" });

      doc.setDrawColor(A.rule[0], A.rule[1], A.rule[2]);
      doc.setLineWidth(u(0.8));
      doc.line(MARGIN, u(25.5), pW - MARGIN, u(25.5));
    }

    /* ── Summary chips. Four reports already compute a
       server-side summary and had nowhere to print it. ── */
    function chips(y) {
      var items = o.summary || [];
      if (!items.length) return y;
      var gap = u(3);
      var w = (pW - 2 * MARGIN - gap * (items.length - 1)) / items.length;
      items.forEach(function (kv, i) {
        var x = MARGIN + i * (w + gap);
        doc.setFillColor(A.tint[0], A.tint[1], A.tint[2]);
        doc.setDrawColor(A.rule[0], A.rule[1], A.rule[2]);
        doc.setLineWidth(u(0.2));
        doc.roundedRect(x, y, w, u(13), u(1.6), u(1.6), "FD");
        doc.setFont("helvetica", "normal");
        doc.setFontSize(6.5);
        doc.setTextColor(MUTED[0], MUTED[1], MUTED[2]);
        doc.text(String(kv[0]).toUpperCase(), x + u(3), y + u(5));
        doc.setFont("helvetica", "bold");
        doc.setFontSize(9);
        doc.setTextColor(A.ink[0], A.ink[1], A.ink[2]);
        doc.text(String(kv[1]), x + u(3), y + u(10.5));
      });
      return y + u(17);
    }

    /* ── Footer. Attribution left, identity and page right. ── */
    function footer(pg, total) {
      var y = pH - u(8);
      doc.setDrawColor(HAIRLINE[0], HAIRLINE[1], HAIRLINE[2]);
      doc.setLineWidth(u(0.2));
      doc.line(MARGIN, y - u(3.5), pW - MARGIN, y - u(3.5));
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7);
      doc.setTextColor(FAINT[0], FAINT[1], FAINT[2]);
      doc.text("Generated by Financee ERP   ·   Developed by Maaz Rehan", MARGIN, y);
      doc.text(String(o.title) + "   ·   Page " + pg + " of " + total,
               pW - MARGIN, y, { align: "right" });
    }

    header();
    var startY = chips(u(29));

    var ctx = {
      accent: A, pageWidth: pW, pageHeight: pH, margin: MARGIN,
      startY: startY, ink: INK, muted: MUTED, hairline: HAIRLINE,
      zebra: ZEBRA, formatDate: formatDate, unit: unit, u: u,
      /* A report with a second table — Customer-wise Profit runs a ranking
         and then the grouped detail — passes this as that table's
         didDrawPage, so any page it adds gets the same title block. */
      drawHeader: header,
      /* The head and body styles the first table used, so a second one
         cannot drift from it. */
      tableStyles: function () {
        return {
          theme: "grid",
          headStyles: {
            fillColor: A.tint, textColor: A.ink, fontStyle: "bold",
            fontSize: o.fontSize || 7.5, cellPadding: u(2),
            lineColor: A.rule, lineWidth: u(0.1),
          },
          bodyStyles: {
            fontSize: o.fontSize || 7.5, textColor: INK, cellPadding: u(1.9),
            lineColor: HAIRLINE, lineWidth: u(0.1),
          },
          margin: { left: MARGIN, right: MARGIN, top: u(29), bottom: u(14) },
          didDrawPage: function () { header(); },
        };
      },
    };

    if (typeof o.draw === "function") {
      /* A report whose body is not a table — Monthly Position
         draws label/amount rows by hand. It still gets the
         header, the chips and the footer. */
      o.draw(doc, ctx);
    } else {
      /* A caller may hand over rows, or point at a table already in the
         DOM. The dashboard's modal exports do the latter — the table is
         on screen and re-deriving its rows would be a second source of
         truth for the same numbers. */
      var tableSource = o.html
        ? { html: o.html, useCss: false }
        : { head: [o.head || []], body: o.body || [] };

      doc.autoTable(Object.assign({}, tableSource, {
        startY: startY,
        margin: { left: MARGIN, right: MARGIN, top: u(29), bottom: u(14) },
        theme: "grid",
        headStyles: {
          fillColor: A.tint, textColor: A.ink, fontStyle: "bold",
          fontSize: o.fontSize || 7.5, cellPadding: u(2),
          lineColor: A.rule, lineWidth: u(0.1),
        },
        bodyStyles: {
          fontSize: o.fontSize || 7.5, textColor: INK, cellPadding: u(1.9),
          lineColor: HAIRLINE, lineWidth: u(0.1),
        },
        alternateRowStyles: { fillColor: ZEBRA },
        columnStyles: o.columnStyles,
        didParseCell: o.didParseCell,
        didDrawPage: function () { header(); },
      }));
      if (typeof o.afterTable === "function") {
        o.afterTable(doc, doc.lastAutoTable ? doc.lastAutoTable.finalY : startY, ctx);
      }
    }

    /* Footers last, so every page knows the final page count. */
    var total = doc.internal.getNumberOfPages();
    for (var i = 1; i <= total; i++) { doc.setPage(i); footer(i, total); }
    return doc;
  }

  /** Build and save in one call — what most callers want.
   *
   *  A report gets a date-stamped name so a folder of them sorts. A
   *  transaction document overrides it with opts.filename, because
   *  "Sale_Invoice_373.pdf" is what someone searches for; the date it
   *  happened to be printed is not how anyone looks for an invoice. */
  function save(o) {
    var doc = build(o);
    doc.save(o.filename || filename(o.title, o.generatedAt));
    if (globalThis.FinanceeActivity) globalThis.FinanceeActivity.exported("pdf");
    return doc;
  }

  return {
    ACCENT: ACCENT,
    MODULE_ACCENT: MODULE_ACCENT,
    ROW: ROW,
    build: build,
    save: save,
    filename: filename,
    formatDate: formatDate,
    formatStamp: formatStamp,
  };
});
