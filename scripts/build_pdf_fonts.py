"""Developer-only font build: FontTools required; no runtime toolchain needed.
Rename a DejaVu-derived family and add the three missing catalogue currency
outlines from Noto sources. Both licence notices travel with the derived fonts.
Usage: python scripts/build_pdf_fonts.py DEJAVU_DIR NASKH_TTF BENGALI_TTF
"""
from pathlib import Path
import base64,hashlib,json,runpy,sys
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.transformPen import TransformPen
root=Path(__file__).resolve().parents[1]
output=root/'static/fonts/financee';output.mkdir(parents=True,exist_ok=True)
base=Path(sys.argv[1]);arabic=TTFont(sys.argv[2]);bengali=TTFont(sys.argv[3])
manifest={'family':'Financee Sans','licence':'SIL OFL 1.1, with preserved DejaVu/Bitstream/Arev notices','files':{},'sources':{}}
for path in [base/'DejaVuSans.ttf',base/'DejaVuSans-Bold.ttf',base/'DejaVuSans-Oblique.ttf',base/'DejaVuSans-BoldOblique.ttf',Path(sys.argv[2]),Path(sys.argv[3])]:
 font=TTFont(path);manifest['sources'][path.name]={'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'version':font['name'].getDebugName(5)}
styles={'normal':('DejaVuSans.ttf','Regular'),'bold':('DejaVuSans-Bold.ttf','Bold'),'italic':('DejaVuSans-Oblique.ttf','Italic'),'bolditalic':('DejaVuSans-BoldOblique.ttf','Bold Italic')}
encoded={}
for style,(file,display) in styles.items():
 font=TTFont(base/file)
 needed=[(0x060b,arabic),(0xfdfc,arabic),(0x09f3,bengali)]
 normal=TTFont(base/'DejaVuSans.ttf')
 common=runpy.run_path(str(root/'local/currency_data.py'))['COMMON_SYMBOLS']
 for cp in {ord(c) for value in common.values() for c in value}:
  if cp not in font.getBestCmap() and cp in normal.getBestCmap():needed.append((cp,normal))
 for cp,source in needed:
  cmap=source.getBestCmap();glyphname=cmap[cp];name='financee_currency_'+hex(cp)[2:]
  recording=DecomposingRecordingPen(source.getGlyphSet());source.getGlyphSet()[glyphname].draw(recording)
  pen=TTGlyphPen(None);scale=font['head'].unitsPerEm/source['head'].unitsPerEm
  recording.replay(TransformPen(pen,(scale,0,0,scale,0,0)))
  order=list(font.getGlyphOrder())
  font['glyf'][name]=pen.glyph()
  advance,lsb=source['hmtx'][glyphname];font['hmtx'][name]=(round(advance*scale),round(lsb*scale))
  font.setGlyphOrder(order+[name])
  for table in font['cmap'].tables:
   if table.isUnicode():table.cmap[cp]=name
 for record in list(font['name'].names):
  values={1:'Financee Sans',2:display,3:'FinanceeSans-1.0-'+style,4:'Financee Sans '+display,6:'FinanceeSans-'+style}
  if record.nameID in values:font['name'].setName(values[record.nameID],record.nameID,record.platformID,record.platEncID,record.langID)
 name='FinanceeSans-'+style+'.ttf';target=output/name;font.save(target)
 verified=TTFont(target);coverage=verified.getBestCmap()
 symbols=runpy.run_path(str(root/'local/currency_data.py'))['COMMON_SYMBOLS']
 assert all(ord(c) in coverage for value in symbols.values() for c in value)
 manifest['files'][name]={'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'catalogue_symbols':len(symbols)}
 encoded[style]=base64.b64encode(target.read_bytes()).decode()
(output/'MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n')
(root/'static/js/pdf_fonts.js').write_text('/* Generated by scripts/build_pdf_fonts.py. See static/fonts/financee licences. */\nwindow.FinanceePdfFonts = '+json.dumps(encoded,separators=(',',':'))+';\n')
print('Verified every catalogue currency symbol in all 4 bundled font styles.')
